-- ZEXO clean marketplace schema. All exposed tables have RLS enabled.
create extension if not exists pgcrypto with schema extensions;
create schema if not exists private;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (char_length(username) between 3 and 24),
  display_name text not null default '',
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('creator','admin')),
  created_at timestamptz not null default now(),
  primary key (user_id, role)
);

create table public.creator_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  display_name text not null,
  biography text not null default '' check (char_length(biography) <= 2000),
  website_url text,
  verification_status text not null default 'unverified' check (verification_status in ('unverified','pending','verified','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  description text not null default '',
  icon text,
  active boolean not null default true,
  display_order integer not null default 0
);

create table public.add_ons (
  id uuid primary key default gen_random_uuid(),
  creator_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  title text not null check (char_length(title) between 3 and 100),
  slug text not null unique,
  short_description text not null default '' check (char_length(short_description) <= 240),
  description text not null check (char_length(description) between 10 and 5000),
  thumbnail_path text,
  version text not null default '1.0.0',
  minecraft_versions text[] not null default '{}',
  tags text[] not null default '{}',
  credits text not null default '',
  license text not null default '',
  status text not null default 'draft' check (status in ('draft','pending_review','changes_requested','approved','published','rejected','suspended','archived')),
  moderation_feedback text,
  download_count bigint not null default 0 check (download_count >= 0),
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

create table public.add_on_files (
  id uuid primary key default gen_random_uuid(),
  add_on_id uuid not null references public.add_ons(id) on delete cascade,
  storage_path text not null unique,
  file_name text not null,
  file_type text not null check (file_type in ('mcpack','mcaddon','mcworld','mctemplate','zip')),
  file_size bigint not null check (file_size between 1 and 104857600),
  file_version text not null default '1.0.0',
  scan_status text not null default 'pending' check (scan_status in ('pending','clean','quarantined','rejected')),
  created_at timestamptz not null default now()
);

create table public.add_on_images (
  id uuid primary key default gen_random_uuid(),
  add_on_id uuid not null references public.add_ons(id) on delete cascade,
  image_path text not null,
  display_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  add_on_id uuid not null references public.add_ons(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, add_on_id)
);

create table public.downloads (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  add_on_id uuid not null references public.add_ons(id) on delete cascade,
  file_id uuid not null references public.add_on_files(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid references auth.users(id) on delete set null,
  add_on_id uuid not null references public.add_ons(id) on delete cascade,
  reason text not null,
  details text not null default '' check (char_length(details) <= 2000),
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now()
);

create table public.moderation_events (
  id uuid primary key default gen_random_uuid(),
  admin_id uuid not null references auth.users(id),
  add_on_id uuid not null references public.add_ons(id) on delete cascade,
  action text not null check (action in ('approve','publish','request_changes','reject','suspend','restore')),
  reason text not null default '',
  created_at timestamptz not null default now()
);

create table public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  message text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.admin_audit_logs (
  id uuid primary key default gen_random_uuid(),
  admin_id uuid not null references auth.users(id),
  action text not null,
  target_type text not null,
  target_id text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

